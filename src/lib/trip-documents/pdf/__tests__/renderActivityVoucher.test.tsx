// @vitest-environment node
import { isValidElement, type ReactNode } from "react";
import { expect, it, vi } from "vitest";
import type { ActivityVoucherDocument } from "@/lib/types/ActivityVoucher";
import { renderActivityVoucher } from "../renderActivityVoucher";
import { ActivityVoucherPdf } from "../ActivityVoucherPdf";
const document: ActivityVoucherDocument = {
  template: "activity-voucher",
  templateVersion: 1,
  label: "Día de spa",
  locale: "es",
  country: "AR",
  data: {
    participants: "Ana y José",
    date: "2026-10-02",
    time: "10:00",
    provider: {
      name: "Río Spa",
      address: "Calle 1",
      contact: "Recepción",
      locationUrl: "https://example.com/map",
      providerUrl: "https://example.com/spa",
    },
    program: [
      {
        id: "spa",
        title: "Circuito de agua",
        description: "Relajación y café",
      },
    ],
    inclusions: [{ id: "meal", title: "Almuerzo" }],
    recommendations: "Traer identificación",
  },
};
function text(node: ReactNode): string {
  if (Array.isArray(node)) return node.map(text).join(" ");
  if (isValidElement<{ children?: ReactNode }>(node))
    return text(node.props.children);
  return typeof node === "string" || typeof node === "number"
    ? String(node)
    : "";
}
it.each(["en", "es"] as const)(
  "renders real %s PDF bytes without fetching authored links",
  async (locale) => {
    const fetch = vi
      .spyOn(globalThis, "fetch")
      .mockRejectedValue(new Error("network forbidden"));
    try {
      const result = await renderActivityVoucher({ ...document, locale });
      expect(result.ok).toBe(true);
      if (result.ok)
        expect(result.buffer.subarray(0, 5).toString()).toBe("%PDF-");
      expect(
        fetch.mock.calls.filter(([url]) => /^https?:/.test(String(url))),
      ).toHaveLength(0);
    } finally {
      fetch.mockRestore();
    }
  },
);
it("renders every authored field and localizes headings without inferred claims", () => {
  const content = text(ActivityVoucherPdf({ document }));
  expect(content).toContain("Circuito de agua");
  expect(content).toContain("Ana y José");
  expect(content).toContain("Traer identificación");
  expect(content).not.toContain("Confirmado");
  expect(content).not.toContain("Estado de pago");
  const authored = {
    ...document,
    data: {
      ...document.data,
      holder: "Ana",
      issueDate: "2026-09-23",
      reservationReference: "REF-123",
      paymentWording: "Pay at venue",
      supplierConfirmation: "Supplier verified",
    },
  };
  const result = text(ActivityVoucherPdf({ document: authored }));
  for (const value of [
    "Ana",
    "REF-123",
    "Pay at venue",
    "Supplier verified",
    "Recepción",
    "Almuerzo",
  ])
    expect(result).toContain(value);
  expect(
    text(ActivityVoucherPdf({ document: { ...document, locale: "en" } })),
  ).toContain("Program");
});
it.each([
  { ...document, locale: "fr" },
  { ...document, data: { ...document.data, program: [] } },
  {
    ...document,
    data: {
      ...document.data,
      provider: { ...document.data.provider, locationUrl: "http://unsafe" },
    },
  },
])("rejects invalid generation input before rendering", async (input) => {
  const render = vi.fn();
  const result = await renderActivityVoucher(input, render);
  expect(result.ok).toBe(false);
  expect(render).not.toHaveBeenCalled();
});
it("bounds generated bytes and propagates renderer failures", async () => {
  await expect(
    renderActivityVoucher(
      document,
      vi.fn().mockResolvedValue(Buffer.alloc(4 * 1024 * 1024 + 1)),
    ),
  ).rejects.toThrow("DOCUMENT_PDF_TOO_LARGE");
  expect(
    (
      await renderActivityVoucher(
        document,
        vi.fn().mockResolvedValue(Buffer.alloc(4 * 1024 * 1024)),
      )
    ).ok,
  ).toBe(true);
  await expect(
    renderActivityVoucher(
      document,
      vi.fn().mockRejectedValue(new Error("render failed")),
    ),
  ).rejects.toThrow("render failed");
});
